#!/usr/bin/env node
// Aprovação pelos sócios (CEO 06/11/2026 — "nada deve ficar parado; deve fluir com OK de qualquer um de nós").
// Rodado pelo .github/workflows/bandeja-socios.yml (código da MAIN). Duas mãos:
//   1) ESPELHO: lê no GitHub as PRs abertas com `revisao-eng-chefe` cujo último parecer do revisor é "BANDEJA DO CEO"
//      (sem `ceo-aprovado` e sem MERGE AUTORIZADO depois) e grava a lista em erp_pr_bandeja (fn_pr_bandeja_sincronizar).
//   2) ENTREGA: para cada decisão de sócio ainda não entregue (fn_pr_aprovacao_pendentes), comenta na PR quem decidiu,
//      quando, a justificativa e o patch-id; se APROVADA põe `ceo-aprovado` (o revisor e a fila já entendem); marca
//      entregue (fn_pr_aprovacao_marcar). A etiqueta vai com o PAT (FILA_MERGE_TOKEN) para acordar o revisor.
// Só fetch nativo, sem dependências. Supabase pela REST com a service_role (canal de serviço).

const REPO = process.env.REPO
const GH = 'https://api.github.com'

export const PRIMEIRA_LINHA = (b) => String(b ?? '').split('\n')[0].trim()
export const ehBandeja = (b) => /^BANDEJA DO CEO\b/i.test(PRIMEIRA_LINHA(b))
export const ehAutorizacao = (b) => /^MERGE AUTORIZADO #\d+ — gilberto-revisor · patch-id [0-9a-f]{40}\b/.test(PRIMEIRA_LINHA(b))
export const ehAjustes = (b) => /^AJUSTES ANTES DO MERGE\b/i.test(PRIMEIRA_LINHA(b))
export const patchIdDe = (b) => (/patch-id[\s\S]{0,30}?(?<![0-9a-f])([0-9a-f]{40})(?![0-9a-f])/i.exec(String(b ?? '')) || [])[1] || null
export function codeDoCorpo(corpo) {
  const m = /^[ \t>*_-]*Code:[ \t*_]*([A-Za-z0-9][A-Za-z0-9._-]*)/m.exec(String(corpo ?? ''))
  return m ? m[1].toLowerCase() : null
}

// A PR está na bandeja quando o ÚLTIMO parecer do revisor (bandeja, autorização ou ajustes) é a bandeja.
export function itemDaBandeja(pr, comentarios) {
  const labels = (pr.labels ?? []).map((l) => (typeof l === 'string' ? l : l?.name))
  if (pr.draft || labels.includes('ceo-aprovado') || !labels.includes('revisao-eng-chefe')) return null
  const pareceres = comentarios.filter((c) => ehBandeja(c.body) || ehAutorizacao(c.body) || ehAjustes(c.body))
  const ultimo = pareceres.at(-1)
  if (!ultimo || !ehBandeja(ultimo.body)) return null
  return {
    pr: pr.number, titulo: String(pr.title ?? ''), url: pr.html_url ?? null, code: codeDoCorpo(pr.body),
    patch_id: patchIdDe(ultimo.body),
    motivo: String(ultimo.body).replace(/\n---\n_Generated by[\s\S]*$/, '').slice(0, 4000),
  }
}

export function comentarioDecisao(d) {
  const quando = new Date(d.em).toLocaleString('pt-BR', { timeZone: 'America/Sao_Paulo' })
  const titulo = d.decisao === 'aprovada' ? `OK DE SÓCIO #${d.pr} — ${d.por}` : `RECUSADA POR SÓCIO #${d.pr} — ${d.por}`
  return `${titulo}\n\n` +
    `${d.decisao === 'aprovada' ? 'Aprovada' : 'Recusada'} no ERP (aba Codes › Aprovações) em ${quando}` +
    `${d.patch_id ? ` para o patch-id \`${d.patch_id}\`` : ''}.\n\n**Justificativa:** ${d.justificativa}\n\n` +
    (d.decisao === 'aprovada'
      ? 'Etiqueta `ceo-aprovado` posta em nome dos sócios (CEO 06/11: Gilberto, Rodrigo e Jordana aprovam igual). O revisor reautoriza na próxima passada.'
      : 'A PR fica parada; o Code que a abriu deve tratar o motivo acima.') +
    '\n<!-- bandeja-socios -->'
}

async function gh(caminho, init = {}, token = process.env.GH_TOKEN) {
  const r = await fetch(`${GH}${caminho}`, { ...init, headers: { Authorization: `Bearer ${token}`, Accept: 'application/vnd.github+json', 'Content-Type': 'application/json', ...(init.headers ?? {}) } })
  if (!r.ok) throw new Error(`GitHub ${init.method ?? 'GET'} ${caminho}: ${r.status} ${await r.text()}`)
  return r.status === 204 ? null : r.json()
}
async function ghTodas(caminho) {
  const out = []
  for (let p = 1; p <= 10; p++) {
    const sep = caminho.includes('?') ? '&' : '?'
    const pg = await gh(`${caminho}${sep}per_page=100&page=${p}`)
    out.push(...pg)
    if (pg.length < 100) break
  }
  return out
}
async function rpc(fn, args = {}) {
  const url = process.env.SUPABASE_URL, key = process.env.SUPABASE_SERVICE_ROLE_KEY
  if (!url || !key) throw new Error('SUPABASE_URL/SUPABASE_SERVICE_ROLE_KEY ausentes')
  const r = await fetch(`${url.replace(/\/$/, '')}/rest/v1/rpc/${fn}`, { method: 'POST', body: JSON.stringify(args),
    headers: { apikey: key, Authorization: `Bearer ${key}`, 'Content-Type': 'application/json' } })
  if (!r.ok) throw new Error(`Supabase ${fn}: ${r.status} ${await r.text()}`)
  return r.json()
}

async function main() {
  if (!REPO) throw new Error('REPO ausente')
  // 1) espelho da bandeja
  const issues = await ghTodas(`/repos/${REPO}/issues?state=open&labels=revisao-eng-chefe`)
  const itens = []
  // a lista de issues já traz título, corpo, etiquetas e rascunho: só busca comentários de quem pode estar na bandeja
  const candidatas = issues.filter((x) => x.pull_request && !x.draft && !(x.labels ?? []).some((l) => l?.name === 'ceo-aprovado'))
  for (const i of candidatas) {
    const pr = { ...i, html_url: i.pull_request?.html_url ?? i.html_url }
    const com = await ghTodas(`/repos/${REPO}/issues/${i.number}/comments`)
    const it = itemDaBandeja(pr, com)
    if (it) itens.push(it)
  }
  const s = await rpc('fn_pr_bandeja_sincronizar', { p_itens: itens })
  console.log(`bandeja: ${itens.length} PR(s) esperando sócio · ${JSON.stringify(s)}`)

  // 2) entrega das decisões
  const pend = await rpc('fn_pr_aprovacao_pendentes')
  const pat = process.env.FILA_MERGE_TOKEN || process.env.GH_TOKEN
  for (const d of pend ?? []) {
    let res
    try {
      const pr = await gh(`/repos/${REPO}/pulls/${d.pr}`)
      if (pr.state !== 'open') res = `PR ${pr.merged ? 'já publicada' : 'fechada'}: nada a fazer`
      else {
        await gh(`/repos/${REPO}/issues/${d.pr}/comments`, { method: 'POST', body: JSON.stringify({ body: comentarioDecisao(d) }) }, pat)
        if (d.decisao === 'aprovada') await gh(`/repos/${REPO}/issues/${d.pr}/labels`, { method: 'POST', body: JSON.stringify({ labels: ['ceo-aprovado'] }) }, pat)
        res = d.decisao === 'aprovada' ? 'comentado + ceo-aprovado' : 'comentado (recusada)'
      }
    } catch (e) { res = `erro: ${String(e.message).slice(0, 200)}`; console.error(res); continue }
    await rpc('fn_pr_aprovacao_marcar', { p_id: d.id, p_resultado: res })
    console.log(`#${d.pr} ${d.decisao} por ${d.por}: ${res}`)
  }
}

if (import.meta.url === `file://${process.argv[1]}`) main().catch((e) => { console.error(e); process.exit(1) })
