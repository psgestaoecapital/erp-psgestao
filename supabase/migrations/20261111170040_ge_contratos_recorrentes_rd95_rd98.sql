-- RD-98 p3 · origem do dado: as RPCs que a tela passa a chamar (sem duplicar)
UPDATE public.system_screens
   SET rpcs_chamadas = (
         SELECT array_agg(DISTINCT x ORDER BY x)
           FROM unnest(COALESCE(rpcs_chamadas, ARRAY[]::text[]) || ARRAY['fn_contrato_encerrar','fn_contrato_excluir']::text[]) AS x
       )
 WHERE rota = '/dashboard/cadastros/contratos-recorrentes'
   AND NOT (COALESCE(rpcs_chamadas, ARRAY[]::text[]) @> ARRAY['fn_contrato_encerrar','fn_contrato_excluir']::text[]);
